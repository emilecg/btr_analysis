from sklearn.ensemble import RandomForestRegressor

# Prepare input data for machine learning
X = np.column_stack((raw_data_A_flat, raw_data_B_flat))
y = observed_intersection

# Train a Random Forest Regressor
model = RandomForestRegressor()
model.fit(X, y)

# Predict intersections and reshape to matrix form for plotting
predicted_intersections = model.predict(X)
predicted_intersection_matrix = predicted_intersections.reshape(observed_intersection_matrix.shape)


# Load the "combined_wew_plop.csv" data
df = pd.read_csv("dwew_btr_distance_matrix_tots.csv", index_col=0)

# Extract sample names and total values
sample_names = df.columns.tolist()[1:]  # Exclude sample name label
total_values = df.iloc[0, 1:].to_numpy()  # Total values row (second row), excluding the name column

# Initialize an empty DataFrame for adjusted values
adjusted_df = pd.DataFrame(index=sample_names, columns=sample_names)

# Iterate over the distance matrix to apply the adjustment
for i, name_i in enumerate(sample_names):
    for j, name_j in enumerate(sample_names):
        # Check if the current cell in the original matrix is empty
        if pd.isna(df.iloc[i + 1, j + 1]):
            adjusted_df.loc[name_i, name_j] = ""  # Preserve empty cells
        else:
            # Prepare input pair for prediction
            input_pair = np.array([[total_values[i], total_values[j]]])
            predicted_value = model.predict(input_pair)[0]
            adjusted_value = df.iloc[i + 1, j + 1] - predicted_value
            adjusted_df.loc[name_i, name_j] = adjusted_value
            
            
